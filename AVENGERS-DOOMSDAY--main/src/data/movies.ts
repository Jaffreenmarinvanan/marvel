export function getMovieBySlug(slug: string): Movie | undefined {
  return movies.find((m) => m.slug === slug);
}

export function getMoviesByPhase(phase: number): Movie[] {
  return movies.filter((m) => m.phase === phase);
}

export function getMoviesByType(type: 'movie' | 'series'): Movie[] {
  return movies.filter((m) => m.type === type);
}

export function searchMovies(query: string): Movie[] {
  const q = query.toLowerCase();
  return movies.filter(
    (m) =>
      m.title.toLowerCase().includes(q) ||
      m.director.toLowerCase().includes(q) ||
      m.synopsis.toLowerCase().includes(q)
  );
}

export const moviesByPhase = (phase: number): Movie[] => movies.filter((m) => m.phase === phase);
export const moviesByReleaseOrder = [...movies].sort((a, b) => a.releaseOrder - b.releaseOrder);
export const moviesByChronOrder = [...movies].sort((a, b) => a.chronologicalOrder - b.chronologicalOrder);
export const allMoviesOnly = movies.filter((m) => m.type === 'movie');
export const allSeriesOnly = movies.filter((m) => m.type === 'series');
