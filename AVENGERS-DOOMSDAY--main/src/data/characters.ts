export const getCharacterBySlug = (slug: string) => characters.find(c => c.slug === slug);

export function characterProfilePath(slug: string) {
  const character = getCharacterBySlug(slug);
  if (character?.type === 'villain') return `/villains/${slug}`;
  if (character?.type === 'hero' || character?.type === 'anti-hero') return `/heroes/${slug}`;
  return `/characters/${slug}`;
}

export const heroes = characters.filter(c => c.type === 'hero' || c.type === 'anti-hero');
export const villains = characters.filter(c => c.type === 'villain');
export const antiHeroes = characters.filter(c => c.type === 'anti-hero');
export const supporting = characters.filter(c => c.type === 'supporting');
